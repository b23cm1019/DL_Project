# hits a 12 h partition limit resumes losing at most 10k updates.
SCREENING = {
    "s3_c2_constant": "Abl_C2_Constant", "s3_s1_typeonly": "Abl_S1_TypeOnly", "s3_k1_nocal": "Abl_K1_NoCalibrator",
    "s3_k2_nogate": "Abl_K2_NoGate", "s3_k3_nocal_nogate": "Abl_K3_NoCalNoGate", "s3_k4_nokl": "Abl_K4_NoKL",
    "s3_k5_fixednull": "Abl_K5_FixedNull", "s3_f1_noskip": "Abl_F1_NoSkipFiLM", "s3_f2_middleonly": "Abl_F2_MiddleOnly",
    "s3_f4_randinit": "Abl_F4_RandomInitFiLM", "s3_s4_shared": "Abl_S4_SharedAnalysis", "s3_t3_nostage2": "Abl_T3_NoStage2",
}


def screening():
    swaps = (
        ("# Budget: 200k updates on Plan B's 750k cosine curve -> compare with Plan B's net_g_200000.pth.",
         "# Budget: 100k SCREENING updates on Plan B's 750k cosine curve -> compare with Plan B's and DCPT's\n"
         "# net_g_100000.pth. Checkpoints every 10k (a 12 h job limit loses at most 10k on resume)."),
        ("  total_iter: 200000", "  total_iter: 100000"),
        ("save_checkpoint_freq: 50000", "save_checkpoint_freq: 10000"),
        ("val: {val_freq: 100000", "val: {val_freq: 50000"),
    )
    for stem, name in SCREENING.items():
        text = (OUT / f"{stem}.yml").read_text()
        for old, new in swaps:
            if old not in text:
                raise ValueError(f"{stem}: expected line not found: {old}")
            text = text.replace(old, new)
        # Rename the experiment (name, experiments_root, tb_logger) only, never the analysis paths.
        for key in ("name: ", "/ablations/experiments/", "/ablations/tb_logger/"):
            text = text.replace(f"{key}{name}\n", f"{key}{name}_100k\n")
        if text.count(f"{name}_100k") != 3:
            raise ValueError(f"{stem}: expected 3 renamed fields, found {text.count(name + '_100k')}")
        (OUT / f"{stem}_100k.yml").write_text(text)


if __name__ == "__main__":
    main()
