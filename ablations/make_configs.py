def fill(template, values):
    text = template
    for key, value in values.items():
        text = text.replace(f"<<{key}>>", value)
    if "<<" in text:
        raise ValueError(f"unfilled token in template: {text[text.index('<<'):][:40]}")
    return text


def lines(*items, indent=2):
    return "".join(" " * indent + item + "\n" for item in items)


def stage3(file, name, abl_id, question, change, *, net="SeverityConditionedFullNAFNet", condition_mode="full",
           gate="true", calibrator="true", network_extra=(), dataset="SeverityConditionedPairedDataset",
           dataset_extra=(), dataset_val_extra=None, manifests="@SHARED_ROOT@/severity_full/manifests",
           pretrain=f"{S2_MAIN}/net_g_latest.pth", analysis_dir=S2_MAIN, extractor_net=None, test_transform=None,
           kl="0.01", train_extra=(), find_unused="false"):
    dataset_val_extra = dataset_extra if dataset_val_extra is None else dataset_val_extra
    extra = []
    if extractor_net:
        extra.append(f"    extractor_net: {extractor_net}")
    if test_transform:
        extra.append(f"  test_condition_transform: {test_transform}")
    values = {
        "ID": abl_id, "QUESTION": question, "CHANGE": change, "NAME": name, "GEN": f"{analysis_dir}/net_g_latest.pth",
        "EXT": f"{analysis_dir}/net_extractor_latest.pth", "ABLATION_EXTRA": "".join(e + "\n" for e in extra),
        "DATASET": dataset, "MANIFESTS": manifests,
        "DATASET_TRAIN_EXTRA": lines(*dataset_extra, indent=4), "DATASET_VAL_EXTRA": lines(*dataset_val_extra, indent=4),
        "NET": net, "CONDITION_MODE": condition_mode, "GATE": gate, "CALIBRATOR": calibrator,
        "NETWORK_EXTRA": lines(*network_extra), "EXP": EXP, "PRETRAIN": pretrain, "KL": kl,
        "TRAIN_EXTRA": lines(*train_extra),
        # Calibrator / gate parameters that a variant never uses must be tolerated by DDP.
        "FIND_UNUSED": find_unused,
    }
    (OUT / file).write_text(fill(STAGE3, values))


def extractor_block(extra=()):
    return lines("type: AblationSeverityExtractor", "feature_dims: [64, 128, 256, 512]", "middle_dim: 1024",
                 "hidden_dim: 256", "num_types: 4", "num_bins: 4", *extra)


def chain(key, name, abl_id, question, change, *, syn=SYN_A, loss="ordinal", extractor_extra=(),
          extractor_inline_extra="", cdd_extra=(), stage1=True, holdout=None):
    """Stage 1 (optional) -> Stage 2 -> Stage 3 for one analysis-side variant."""
    s1_dir = f"{EXP}/{name}_Stage1/models" if stage1 else S1_MAIN
    if stage1:
        (OUT / f"{key}_stage1.yml").write_text(fill(STAGE1, {
            "ID": abl_id, "QUESTION": question, "CHANGE": change, "NAME": f"{name}_Stage1", "SYN": syn,
            "EXTRACTOR_BLOCK": extractor_block(extractor_extra), "EXP": EXP, "LOSS": loss}))
    cdd_dataset = "AblationSeverityDCPTPairedDataset" if holdout else "SeverityDCPTPairedDataset"
    cdd_lines = lines(f"exclude_settings: [{', '.join(holdout)}]", indent=4) if holdout else ""
    (OUT / f"{key}_stage2.yml").write_text(fill(STAGE2, {
        "ID": abl_id, "QUESTION": question, "CHANGE": change, "NAME": f"{name}_Stage2", "SYN": syn,
        "CDD_DATASET": cdd_dataset, "CDD": CDD_MANIFESTS, "CDD_EXTRA": cdd_lines,
        "EXTRACTOR_BLOCK": extractor_block(extractor_extra), "EXP": EXP, "S1": s1_dir, "LOSS": loss}))
    s2_dir = f"{EXP}/{name}_Stage2/models"
    extractor_net = EXTRACTOR_BASE + extractor_inline_extra + "}"
    common = dict(manifests=f"@OUT_ROOT@/ablations/manifests/{key}", pretrain=f"{s2_dir}/net_g_latest.pth",
                  analysis_dir=s2_dir, extractor_net=extractor_net)
    return common


def dcpt_holdout():
    source = (ROOT / "options" / "cdd_experiments" / "dcpt_cdd11_finetune_750k.yml").read_text()
    kept = []
    for line in source.splitlines():
        if line.startswith("  train_11:"):
            continue  # low_haze_snow removed from training (held out)
        if line.startswith("name:"):
            line = "name: DCPT_X3_Holdout_LHS"
        if line.strip().startswith("experiments_root:"):
            line = (f"  experiments_root: {EXP}/DCPT_X3_Holdout_LHS\n"
                    "  tb_logger: @OUT_ROOT@/ablations/tb_logger/DCPT_X3_Holdout_LHS")
        if line.strip().startswith("total_iter: 750000"):
            line = line.replace("750000", "200000")
        kept.append(line.replace("/scratch/p26cs0003/krish", "@SHARED_ROOT@"))
    header = ("# X3 baseline: DCPT fine-tuning with low_haze_snow held out of training (val keeps all 11).\n"
              "# Generated by ablations/make_configs.py from dcpt_cdd11_finetune_750k.yml; 200k updates on its\n"
              "# 750k cosine curve -> compare with DCPT's net_g_200000.pth and with Abl_X3_Holdout_LHS.\n")
    (OUT / "dcpt_x3_holdout_lhs.yml").write_text(header + "\n".join(kept) + "\n")


